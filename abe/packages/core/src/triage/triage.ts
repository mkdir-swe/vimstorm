/**
 * Triage (spec #35 stories 9–12, ticket #76): a verdict per backlog item (a card not running, an
 * open GitHub issue): ready for an agent, needs info, too big, or not for an agent, each with its reason.
 * One one-shot with core's triage skill decides; the rules around it are here: which items, the
 * prompt and the verdicts' shape, and what each verdict may write (`WRITES`). Nothing is written
 * by triage itself: `apply` asks a needs-info card's question, `launch` runs the ready cards.
 */
import { z } from 'zod';
import { carriesTag, type CardComment, type CardData, parseCardId } from '../board/board';
import { askingJson, readJsonAnswer } from './one-shot';
import { skillBody } from '../skills/skills';
import { type OpenIssue } from '../board/tracking';
import triageSkill from '../../skills/triage/one-shot.md' with { type: 'text' };

/** Core's triage one-shot prompt (`skills/triage/one-shot.md`: upstream's triage, cut to four verdicts). */
export const TRIAGE_SKILL: string = skillBody(triageSkill);

export const VERDICTS = ['ready', 'needs-info', 'too-big', 'not-for-agent'] as const;
export type Verdict = (typeof VERDICTS)[number];

export const SOURCES = ['azure', 'github'] as const;
export type Source = (typeof SOURCES)[number];

/** Mine this sprint (the default), or the team's whole backlog (`--team`). */
export const SCOPES = ['mine', 'team'] as const;

/** The tag a needs-info card gets beside its question. */
export const NEEDS_INFO_TAG = 'needs-info';

/** Every comment and issue triage writes starts so (upstream triage's disclaimer). */
export const TRIAGE_DISCLAIMER = '> *This was generated by AI during triage.*';

/** What a verdict lets Abe write: launch a run, ask the question (comment and tag), or nothing. */
export type Write = 'launch' | 'ask' | null;

/**
 * What each verdict may write, by where the item lives. Only cards are written: a GitHub issue's
 * verdict is for reading (it launches once it has a card; its questions go on GitHub by hand).
 */
export const WRITES: Readonly<Record<Verdict, Readonly<Record<Source, Write>>>> = {
  ready: { azure: 'launch', github: null },
  'needs-info': { azure: 'ask', github: null },
  'too-big': { azure: null, github: null },
  'not-for-agent': { azure: null, github: null },
};

/** One item as the one-shot reads it. `id` is `AB#<n>` for a card, `<owner/repo>#<n>` for an issue. */
export type TriageInput = {
  id: string;
  source: Source;
  title: string;
  url: string;
  /** The card's type, or `Issue`. */
  kind: string;
  /** The card's state; `open` for an issue. */
  state: string;
  tags: string[];
  assignee: string | null;
  description: string;
  acceptanceCriteria: string;
  /** A card's comments since triage asked its question, the answer among them (#77); none: absent. */
  thread?: CardComment[] | undefined;
};

export const cardItemId = (card: number) => `AB#${card}`;

export const cardInput = (c: CardData, thread: readonly CardComment[] = []): TriageInput => ({
  id: cardItemId(c.id),
  source: 'azure',
  title: c.title,
  url: c.url,
  kind: c.type,
  state: c.state,
  tags: c.tags,
  assignee: c.assignee?.name ?? null,
  description: c.description,
  acceptanceCriteria: c.acceptanceCriteria,
  ...(thread.length === 0 ? {} : { thread: [...thread] }),
});

export const issueInput = (i: OpenIssue): TriageInput => ({
  id: `${i.repo}#${i.number}`,
  source: 'github',
  title: i.title,
  url: i.url,
  kind: 'Issue',
  state: 'open',
  tags: i.labels,
  assignee: null,
  description: i.body,
  acceptanceCriteria: '',
});

export const SkippedItem = z.object({
  id: z.string(),
  source: z.enum(SOURCES),
  title: z.string(),
  why: z.literal('running'),
});
export type SkippedItem = z.infer<typeof SkippedItem>;

/**
 * Which items are triaged: every card but those running (a session or a Factory run on it), then
 * every open issue but a Factory run's spec and slices (#200: its card's work, closed by its pull
 * request's merge, never work of their own), nor one labelled `board.notTag` (the board's query
 * leaves such cards out; GitHub's issues list cannot). Running cards are skipped, listed with why.
 */
export const itemsToTriage = (o: {
  cards: readonly CardData[];
  issues: readonly OpenIssue[];
  running: ReadonlySet<number>;
  /** The Factory runs' spec issues and slices (`specIssuesOf`). */
  specIssues?: ReadonlySet<string>;
  /** The comments since triage asked, of the cards it asked (`askedCards`, `answersOf`). */
  threads?: ReadonlyMap<number, readonly CardComment[]>;
  /** `board.notTag`: an issue labelled so is left out. */
  notTag?: string;
}): { items: TriageInput[]; skipped: SkippedItem[] } => ({
  items: [
    ...o.cards
      .filter((c) => !o.running.has(c.id))
      .map((c) => cardInput(c, o.threads?.get(c.id) ?? [])),
    ...o.issues
      .filter((i) => !(o.specIssues?.has(`${i.repo}#${i.number}`.toLowerCase()) ?? false))
      .filter((i) => o.notTag === undefined || !carriesTag(i.labels, o.notTag))
      .map(issueInput),
  ],
  skipped: o.cards
    .filter((c) => o.running.has(c.id))
    .map((c): SkippedItem => ({
      id: cardItemId(c.id),
      source: 'azure',
      title: c.title,
      why: 'running',
    })),
});

/**
 * The Factory runs' spec issues and slices that are not work of their own (#200), as
 * `owner/repo#n` in lower case: a run's still going, or its pull request merged (closing them).
 * A run done without a merge (dropped, a question, its pull request closed) leaves them open, so
 * triage offers them again.
 */
export const specIssuesOf = (
  runs: readonly { specIssues: readonly string[]; done: boolean; merged: boolean }[],
): Set<string> =>
  new Set(
    runs
      .filter((r) => !r.done || r.merged)
      .flatMap((r) => r.specIssues.map((i) => i.toLowerCase())),
  );

/**
 * The cards running now: a session that has not ended, or a Factory run that is not done (one
 * waiting on you after its session ended still holds its card).
 */
export const runningCards = (o: {
  sessions: readonly { card: number; state: string }[];
  runs: readonly { card: number; done: boolean }[];
}): Set<number> =>
  new Set([
    ...o.sessions.filter((s) => s.state !== 'ended').map((s) => s.card),
    ...o.runs.filter((r) => !r.done).map((r) => r.card),
  ]);

/**
 * The cards whose comments the next triage reads (#77): those tagged needs-info, and the last
 * triage's needs-info ones (their tag may be gone with the answer). The others' comments are not
 * read: a card triage never asked has no answer to find.
 */
export const askedCards = (
  cards: readonly CardData[],
  last: readonly TriagedItem[] | undefined,
): number[] => {
  const asked = new Set(
    (last ?? []).filter((i) => i.verdict === 'needs-info').map((i) => i.id.toLowerCase()),
  );

  return cards
    .filter(
      (c) =>
        c.tags.some((t) => t.toLowerCase() === NEEDS_INFO_TAG) ||
        asked.has(cardItemId(c.id).toLowerCase()),
    )
    .map((c) => c.id);
};

/** A card's comments from triage's own question on (its answer follows); none when it never asked. */
export const answersOf = (comments: readonly CardComment[]): CardComment[] => {
  const marker = plainWords(TRIAGE_DISCLAIMER);
  const at = comments.findIndex((c) => plainWords(c.text).includes(marker));

  return at < 0 ? [] : comments.slice(at);
};

/** Each item's long text is cut here, so one huge card cannot crowd out the rest. */
const ITEM_TEXT_MAX = 4000;

const clip = (text: string) =>
  text.length <= ITEM_TEXT_MAX ? text : `${text.slice(0, ITEM_TEXT_MAX)} …(cut)`;

const itemBlock = (i: TriageInput) =>
  [
    `## ${i.id}`,
    '',
    `- title: ${i.title}`,
    `- kind: ${i.kind} (${i.state})`,
    ...(i.tags.length === 0 ? [] : [`- tags: ${i.tags.join(', ')}`]),
    ...(i.assignee === null ? [] : [`- assigned to: ${i.assignee}`]),
    '',
    '### Description',
    '',
    i.description.trim() === '' ? '(none)' : clip(i.description.trim()),
    ...(i.acceptanceCriteria.trim() === ''
      ? []
      : ['', '### Acceptance criteria', '', clip(i.acceptanceCriteria.trim())]),
    ...(i.thread === undefined || i.thread.length === 0
      ? []
      : [
          '',
          '### Since triage asked',
          '',
          clip(i.thread.map((c) => `${c.by}, ${c.at.slice(0, 10)}: ${c.text.trim()}`).join('\n\n')),
        ]),
  ].join('\n');

/** The answer's shape, as the prompt shows it. */
const ANSWER_SHAPE = `{"verdicts": [{"id": "<the item's id exactly as given, AB#4 or owner/repo#12>", "verdict": "ready | needs-info | too-big | not-for-agent", "reason": "<one line: what decided it>", "question": "<needs-info only: the one question for its product owner>"}]}

One entry per item, every item once.`;

/** The one-shot's prompt: every item, then the answer's shape. The skill is its system prompt. */
export const triagePrompt = (items: readonly TriageInput[]): string =>
  askingJson(
    [
      `Triage these ${items.length} backlog items with your triage skill: one verdict each, with its reason.`,
      '',
      ...items.map(itemBlock).join('\n\n').split('\n'),
    ].join('\n'),
    ANSWER_SHAPE,
  );

const VerdictAnswer = z
  .object({
    id: z.string(),
    verdict: z.enum(VERDICTS),
    reason: z.string().trim().min(1),
    question: z.string().trim().nullish(),
  })
  .refine((v) => v.verdict !== 'needs-info' || (v.question ?? '') !== '', {
    message: 'a needs-info verdict asks its question',
    path: ['question'],
  });

/** What the one-shot must answer: one verdict per item. */
export const TriageAnswer = z.object({ verdicts: z.array(VerdictAnswer) });

/** One triaged item, as `abe triage` answers it. `question` is set for needs-info only. */
export const TriagedItem = z.object({
  id: z.string(),
  source: z.enum(SOURCES),
  title: z.string(),
  url: z.string(),
  verdict: z.enum(VERDICTS),
  reason: z.string(),
  question: z.string().nullable(),
});
export type TriagedItem = z.infer<typeof TriagedItem>;

/**
 * The one-shot's text as one verdict per item, in the items' order; unreadable when it is no
 * `TriageAnswer`, or misses an item, names one twice or names one not asked about.
 */
export const readTriage = (
  text: string,
  items: readonly TriageInput[],
): { ok: true; items: TriagedItem[] } | { ok: false; message: string } => {
  const read = readJsonAnswer(text, TriageAnswer);

  if (!read.ok) return read;
  const asked = new Set(items.map((i) => i.id));
  const byId = new Map<string, z.output<typeof VerdictAnswer>>();
  const twice: string[] = [];
  const unknown: string[] = [];

  for (const v of read.data.verdicts) {
    if (!asked.has(v.id)) unknown.push(v.id);
    else if (byId.has(v.id)) twice.push(v.id);
    else byId.set(v.id, v);
  }
  const missing = items.filter((i) => !byId.has(i.id)).map((i) => i.id);
  const problems = [
    ...(missing.length === 0 ? [] : [`no verdict for ${missing.join(', ')}`]),
    ...(twice.length === 0 ? [] : [`more than one verdict for ${twice.join(', ')}`]),
    ...(unknown.length === 0 ? [] : [`verdicts for items not asked about: ${unknown.join(', ')}`]),
  ];

  if (problems.length > 0) return { ok: false, message: problems.join('; ') };

  return {
    ok: true,
    items: items.flatMap((i) => {
      const v = byId.get(i.id);

      return v === undefined
        ? []
        : [
            {
              id: i.id,
              source: i.source,
              title: i.title,
              url: i.url,
              verdict: v.verdict,
              reason: v.reason,
              question: v.verdict === 'needs-info' ? (v.question ?? null) : null,
            },
          ];
    }),
  };
};

export const TriageCounts = z.object({
  ready: z.number().int().nonnegative(),
  needsInfo: z.number().int().nonnegative(),
  tooBig: z.number().int().nonnegative(),
  notForAgent: z.number().int().nonnegative(),
  /** Running cards left out. */
  skipped: z.number().int().nonnegative(),
});
export type TriageCounts = z.infer<typeof TriageCounts>;

export const triageCounts = (
  items: readonly { verdict: Verdict }[],
  skipped: number,
): TriageCounts => {
  const of = (v: Verdict) => items.filter((i) => i.verdict === v).length;

  return {
    ready: of('ready'),
    needsInfo: of('needs-info'),
    tooBig: of('too-big'),
    notForAgent: of('not-for-agent'),
    skipped,
  };
};

