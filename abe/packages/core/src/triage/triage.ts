/** The item `text` names in the last triage: a card as `4`, `#4` or `AB#4`; an issue as `owner/repo#12`. */
export const findItem = (items: readonly TriagedItem[], text: string): TriagedItem | undefined => {
  const card = parseCardId(text);
  const id = card === undefined ? text : cardItemId(card);

  return items.find((i) => i.id.toLowerCase() === id.toLowerCase());
};

const VERDICT_WORDS: Readonly<Record<Verdict, string>> = {
  ready: 'ready for an agent',
  'needs-info': 'needs info',
  'too-big': 'too big',
  'not-for-agent': 'not for an agent',
};

export type WriteRefusal = { code: string; message: string };

/** What triage does to a card that an issue cannot have done (#187: said per write). */
const CARD_ONLY: Readonly<Record<'launch' | 'ask', string>> = {
  launch: 'triage launches runs on cards only',
  ask: 'triage asks for info on cards only',
};

/**
 * Whether `want` may be done to the item `text` names in the last triage: its card, or why not
 * (`not-triaged`, `running` for a card it skipped as running, `not-a-card`, `not-ready`,
 * `not-needs-info`).
 */
export const mayWrite = (
  items: readonly TriagedItem[],
  text: string,
  want: 'launch' | 'ask',
  skipped: readonly SkippedItem[] = [],
): { ok: true; item: TriagedItem; card: number } | { ok: false; error: WriteRefusal } => {
  const item = findItem(items, text);

  if (item === undefined) {
    const card = parseCardId(text);
    const ran =
      card === undefined
        ? undefined
        : skipped.find((k) => k.id.toLowerCase() === cardItemId(card).toLowerCase());

    return {
      ok: false,
      error:
        ran === undefined || card === undefined
          ? { code: 'not-triaged', message: `${text} is not in the last triage` }
          : {
              code: 'running',
              message: `${ran.id} was skipped by the last triage: it runs already (abe factory status ${card})`,
            },
    };
  }
  const card = item.source === 'azure' ? parseCardId(item.id) : undefined;

  if (card === undefined)
    return {
      ok: false,
      error: { code: 'not-a-card', message: `${item.id} is a GitHub issue: ${CARD_ONLY[want]}` },
    };
  if (WRITES[item.verdict][item.source] !== want)
    return {
      ok: false,
      error: {
        code: want === 'launch' ? 'not-ready' : 'not-needs-info',
        message: `${item.id} is ${VERDICT_WORDS[item.verdict]}: ${item.reason}`,
      },
    };

  return { ok: true, item, card };
};

/** A needs-info card's comment: the disclaimer, why it needs info, the question. */
export const needsInfoComment = (item: { reason: string; question: string }): string =>
  [
    TRIAGE_DISCLAIMER,
    '',
    '## Triage notes',
    '',
    `**Needs info:** ${item.reason}`,
    '',
    '**What we still need from you:**',
    '',
    `- ${item.question}`,
  ].join('\n');

/** Text as compared: no markdown marks, one space between words, any case. */
const plainWords = (text: string) =>
  text
    .replace(/[*_>#`\\-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();

/** Whether a triage comment on the card already asks `question`: asking again writes nothing. */
export const alreadyAsked = (comments: readonly CardComment[], question: string): boolean => {
  const asked = plainWords(question);
  const marker = plainWords(TRIAGE_DISCLAIMER);

  return comments.some((c) => {
    const text = plainWords(c.text);

    return text.includes(marker) && text.includes(asked);
  });
};

