export const countsText = (c: TriageCounts): string =>
  `${c.ready} ready, ${c.needsInfo} needs info, ${c.tooBig} too big, ${c.notForAgent} not for an agent${c.skipped === 0 ? '' : ` (${c.skipped} running skipped)`}`;

export const triageDoneText = (d: TriageDoneEvent): string =>
  `triage of ${d.items} (${d.scope}): ${countsText(d)}`;

export const triageText = (t: TriageData): string => {
  const where = `${t.board.project} / ${t.board.team}${t.sprint === null ? '' : ` · ${t.sprint}`}${t.repo === null ? '' : ` · ${t.repo}`}`;

  if (t.items.length === 0)
    return `nothing to triage on ${where}${t.skipped.length === 0 ? '' : ` (${t.skipped.length} running)`}\n`;
  const width = Math.max(...t.items.map((i) => i.id.length));
  const verdictWidth = Math.max(...t.items.map((i) => VERDICT_WORDS[i.verdict].length));
  const rows = t.items.map((i) =>
    [
      `${i.id.padEnd(width)}  ${VERDICT_WORDS[i.verdict].padEnd(verdictWidth)}  ${i.title}`,
      `${' '.repeat(width + 2)}${i.reason}`,
      ...(i.question === null ? [] : [`${' '.repeat(width + 2)}asks: ${i.question}`]),
    ].join('\n'),
  );

  return `${where}\n\n${rows.join('\n')}\n\n${countsText(t.counts)}\n`;
};

export const triageApplyText = (a: TriageApplyData): string =>
  a.items.length === 0
    ? 'nothing to apply\n'
    : `${a.items.map((i) => `${i.id}  ${i.result}  ${i.message}`).join('\n')}\n`;

export const triageLaunchText = (l: TriageLaunchData): string =>
  `${[
    ...l.items.map((i) =>
      `${i.id}  ${i.result === 'queued' ? 'Queued' : i.result}  ${i.session ?? i.message}`.trimEnd(),
    ),
    ...(l.local ? [] : [`boxes: ${l.inUse} of ${l.limit} in use before this launch`]),
  ].join('\n')}\n`;
